-- Supabase SQL schema for guestbook and user accounts

-- 1) 방명록 테이블 생성
create table if not exists public.guestbook (
  id bigint generated by default as identity primary key,
  name text not null,
  password text not null,
  message text not null,
  created_at timestamptz not null default now()
);

alter table public.guestbook enable row level security;

drop policy if exists "Allow public select on guestbook" on public.guestbook;
create policy "Allow public select on guestbook"
  on public.guestbook
  for select
  using (true);

drop policy if exists "Allow public insert on guestbook" on public.guestbook;
create policy "Allow public insert on guestbook"
  on public.guestbook
  for insert
  with check (true);

drop policy if exists "Allow public delete on guestbook" on public.guestbook;
create policy "Allow public delete on guestbook"
  on public.guestbook
  for delete
  using (true);

-- 2) 사용자 계정 테이블 생성
create table if not exists public.user_accounts (
  id bigint generated by default as identity primary key,
  username text not null unique,
  phone text not null,
  email text not null,
  password text not null,
  created_at timestamptz not null default now()
);

alter table public.user_accounts enable row level security;

drop policy if exists "Allow public select on user_accounts" on public.user_accounts;
create policy "Allow public select on user_accounts"
  on public.user_accounts
  for select
  using (true);

drop policy if exists "Allow public insert on user_accounts" on public.user_accounts;
create policy "Allow public insert on user_accounts"
  on public.user_accounts
  for insert
  with check (true);

notify pgrst, 'reload schema';
